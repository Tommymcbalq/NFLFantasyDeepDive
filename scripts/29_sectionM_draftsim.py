"""§M2 / §M3 — draft-simulation backtest of five fixed strategies against the ADP null.

Pre-registered in EDA_PLAN6.md §M2/§M3.  EVERYTHING below the "FIXED" banner was fixed
before any strategy was evaluated and no strategy was added after seeing results.

League (the owner's, 10-team frame): 10 teams, snake, PPR, starters
1 QB / 2 RB / 2 WR / 1 TE / 2 FLEX(RB,WR) / 1 DST.  DST is out of scope and is assigned
identically to every team, so the draft is 14 rounds of QB/RB/WR/TE = 140 picks.

FIXED — opponent noise model
  Each opponent team t draws a private board  v_{t,i} = ADP_i + eps_{t,i},
  eps ~ N(0, stdev_i) with stdev_i the FFC across-draft SD of player i's draft slot.
  Rationale: the observed dispersion of a player's draft position across drafts is
  generated by variation across drafters, so a per-drafter perturbation with that SD is
  the generative model that reproduces it.  Calibration is CHECKED (realized simulated SD
  of draft slot vs the FFC stdev) and reported, not tuned.
  Positional need constraints: cap 2 QB and 2 TE per team; no second QB/TE until the
  team's mandatory slots (1 QB, 1 TE, 2 RB, 2 WR, 2 FLEX from RB/WR) can still be met;
  hard force-fill when remaining picks equal remaining mandatory slots.

FIXED — strategies (S0 is the null)
  S0 best available by ADP
  S1 best available by our model board (LOSO theta*; see note below)
  S2 RB-first (RB with the first two picks, then best available by ADP)
  S3 zero-RB (no RB before round 5, then best available by ADP)
  S4 elite-TE (a TE within the first three rounds, then best available by ADP)
  S5 VORP-greedy (maximise marginal expected starting-lineup value at every pick)

  S1 note, stated because it bounds what S1 can show: the project's RB board is
  market-anchored (REPORT §23: neither RB arm was adopted, board_value = m(ADP)), so the
  RB ordering is ADP's.  S1's only deviation from S0 is therefore the WR top-30
  re-ordering by LOSO theta* (results/loso_predictions.csv), applied as a permutation of
  the modelled WRs across the ADP slots they occupy.  All other players keep ADP order.
  theta* is leave-one-season-out, so nothing from season y is used to draft season y.

  S5 note: E[season total | pos, ADP] and the replacement levels R_p come from the
  leave-one-season-out isotonic curve (results/sectionM_adp_value_curve.csv) and from
  replacement levels averaged over the other nine seasons.  No season-y realisation.

FIXED — scoring (§M3)
  Weekly optimal starting lineup on realised weekly PPR; a player with no game that week
  cannot be started.  Reported for weeks 1-14 (fantasy regular season), 15-17 (playoffs)
  and 1-17.  Bench depth is therefore valuable automatically.

FIXED — inference
  N = 200 simulated drafts per (season, slot), common random numbers across strategies.
  d_s = per-season mean (S_k - S0); Diebold-Mariano t on 10 season clusters, t(9).
  BH q = 0.10 across the five comparisons.  This is a NEW declared family; {H5,I3}, {K},
  {L} and {L-EXT} are not reopened.

Outputs: results/strategy_backtest.csv, results/strategy_by_slot.csv,
         results/strategy_distribution.csv, results/sim_calibration.csv
Rerun: python3 scripts/29_sectionM_draftsim.py
"""
