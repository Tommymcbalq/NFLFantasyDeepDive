# ---------------------------------------------------------------- draft engine
MAXQB, MAXTE = 2, 2
# mandatory: 1 QB, 1 TE, 2 RB, 2 WR, 2 FLEX(RB/WR)


def unmet(cnt):
    """remaining mandatory picks given a roster count vector [QB,RB,WR,TE]"""
    q = max(0, 1 - cnt[0]); t = max(0, 1 - cnt[3])
    r = max(0, 2 - cnt[1]); w = max(0, 2 - cnt[2])
    flex = max(0, 6 - (min(cnt[1], 2) + min(cnt[2], 2) + max(0, cnt[1] - 2) + max(0, cnt[2] - 2)))
    return q, r, w, t, flex


def legal_mask(cnt, picks_left):
    """boolean over the 4 positions"""
    ok = np.ones(4, bool)
    if cnt[0] >= MAXQB:
        ok[0] = False
    if cnt[3] >= MAXTE:
        ok[3] = False
    q, r, w, t, flex = unmet(cnt)
    need = q + r + w + t + flex
    if need >= picks_left:                     # force-fill mandatory slots only
        ok[:] = False
        if q:
            ok[0] = True
        if t:
            ok[3] = True
        if r or flex:
            ok[1] = True
        if w or flex:
            ok[2] = True
        if not ok.any():
            ok[:] = True
    else:                                      # no 2nd QB/TE while mandatory unmet
        if cnt[0] >= 1 and (q + r + w + t + flex) > 0:
            ok[0] = False
        if cnt[3] >= 1 and (q + r + w + t + flex) > 0:
            ok[3] = False
    return ok


def opp_pick(order, ptr, taken, pos, cnt, picks_left):
    """ptr may only advance past players who are TAKEN (a monotone property).  A player
    skipped because of a temporary positional-need constraint must remain reachable, so
    the constraint scan starts at ptr and does not persist."""
    while ptr < len(order) and taken[order[ptr]]:
        ptr += 1
    ok = legal_mask(cnt, picks_left)
    j = ptr
    while j < len(order):
        p = order[j]
        if not taken[p] and ok[pos[p]]:
            return p, ptr
        j += 1
    return order[ptr], ptr


def our_pick(S, order, taken, pos, cnt, rnd, picks_left, Ev, Rrep, roster):
    ok = legal_mask(cnt, picks_left)
    if S == "S2" and rnd <= 2:                 # RB with the first two picks
        if (~taken & (pos == 1)).any():
            ok[:] = False; ok[1] = True
    if S == "S3" and rnd <= 4:                 # no RB before round 5
        if (~taken & (pos != 1) & ok[pos]).any():
            ok[1] = False
    if S == "S4" and rnd == 3 and cnt[3] == 0:  # a TE inside the first three rounds
        if (~taken & (pos == 3)).any():
            ok[:] = False; ok[3] = True
    if S == "S5":
        cand = [p for p in order if not taken[p] and ok[pos[p]]][:60]
        if not cand:
            cand = [p for p in order if not taken[p]][:60]
        base = lineup_value(Ev, pos, roster, Rrep)
        best, bi = -1e18, cand[0]
        for p in cand:
            v = lineup_value(Ev, pos, roster + [p], Rrep) - base
            if v > best:
                best, bi = v, p
        return bi
    for p in order:
        if not taken[p] and ok[pos[p]]:
            return p
    for p in order:
        if not taken[p]:
            return p
    return -1


def lineup_value(Ev, pos, roster, Rrep):
    """Expected starting-lineup value of a roster.  Every slot is worth
    max(assigned player, replacement): an unfilled slot takes replacement, and a slot is
    never *forced* to start a sub-replacement player, because a freely available
    replacement-level body can be started instead.  Without the max() the valuer charges
    a negative marginal value for drafting any below-replacement player, which makes the
    greedy refuse whole positions -- see sectionM_notes.md."""
    v = {k: sorted([Ev[p] for p in roster if pos[p] == k], reverse=True) for k in range(4)}
    tot = 0.0
    tot += max(v[0][0], Rrep[0]) if v[0] else Rrep[0]
    tot += max(v[3][0], Rrep[3]) if v[3] else Rrep[3]
    for k, nreq in ((1, 2), (2, 2)):
        got = v[k][:nreq]
        tot += sum(max(x, Rrep[k]) for x in got) + (nreq - len(got)) * Rrep[k]
    Rf = (Rrep[1] + Rrep[2]) / 2
    rest = sorted(v[1][2:] + v[2][2:], reverse=True)[:2]
    tot += sum(max(x, Rf) for x in rest) + (2 - len(rest)) * Rf
    return tot


def score_roster(wkm, pos, roster, w0, w1):
    """weekly optimal lineup 1QB/2RB/2WR/1TE/2FLEX over weeks [w0, w1] inclusive."""
    M = wkm[roster][:, w0 - 1:w1]
    P = pos[roster]
    NEG = -1e9
    out = 0.0
    byp = {k: np.where(P == k)[0] for k in range(4)}
    A = {}
    for k in range(4):
        X = M[byp[k]] if len(byp[k]) else np.zeros((0, M.shape[1]))
        X = np.where(np.isnan(X), NEG, X)
        A[k] = -np.sort(-X, axis=0) if len(X) else X
    def take(k, n):
        X = A[k]
        got = X[:n] if len(X) >= n else np.vstack([X, np.full((n - len(X), M.shape[1]), NEG)])
        rest = X[n:] if len(X) > n else X[:0]
        return got, rest
    qb, _ = take(0, 1); rb, rbr = take(1, 2); wrp, wrr = take(2, 2); te, _ = take(3, 1)
    starters = np.vstack([qb, rb, wrp, te])
    flexpool = np.vstack([rbr, wrr]) if (len(rbr) + len(wrr)) else np.zeros((0, M.shape[1]))
    if len(flexpool):
        flexpool = -np.sort(-flexpool, axis=0)
    fl = flexpool[:2] if len(flexpool) >= 2 else np.vstack(
        [flexpool, np.full((2 - len(flexpool), M.shape[1]), NEG)])
    allst = np.vstack([starters, fl])
    allst = np.where(allst <= NEG / 2, 0.0, allst)
    return float(allst.sum())


def score_static(wkm, pos, roster):
    """DIAGNOSTIC ONLY (family = 0): season totals of the ex-post best 8 starters, i.e.
    the same roster scored as if the lineup were set once for the year.  Contrasting this
    with score_roster isolates how much of a strategy's result is bench/availability."""
    T = np.nan_to_num(wkm[roster], nan=0.0).sum(axis=1)
    P = pos[roster]
    v = {k: sorted(T[P == k], reverse=True) for k in range(4)}
    tot = (v[0][0] if v[0] else 0) + (v[3][0] if v[3] else 0)
    tot += sum(v[1][:2]) + sum(v[2][:2])
    tot += sum(sorted(v[1][2:] + v[2][2:], reverse=True)[:2])
    return float(tot)


# ---------------------------------------------------------------- run
recs, calib = [], []
t0 = time.time()
for y in YEARS:
    S = SEASON[y]
    n, pos, adp, sd = S["n"], S["pos"], S["adp"], S["sd"]
    Rrep = np.array([R_loso[(y, p)] for p in ["QB", "RB", "WR", "TE"]])
    slot_of = np.empty(NTEAM * NROUND, int)
    for r in range(NROUND):
        seq = list(range(NTEAM)) if r % 2 == 0 else list(range(NTEAM))[::-1]
        slot_of[r * NTEAM:(r + 1) * NTEAM] = seq
    drafted_slot = {}
    for myslot in range(NTEAM):
        for sim in range(NSIM):
            rng = np.random.default_rng(1_000_000 * y + 1000 * myslot + sim)
            eps = rng.normal(0, 1, size=(NTEAM, n)) * sd[None, :]
            boards = np.argsort(adp[None, :] + eps, axis=1)
            for st in STRATS:
                taken = np.zeros(n, bool)
                cnt = np.zeros((NTEAM, 4), int)
                rosters = [[] for _ in range(NTEAM)]
                ptr = np.zeros(NTEAM, int)
                for k in range(NTEAM * NROUND):
                    t = slot_of[k]
                    rnd = k // NTEAM + 1
                    left = NROUND - rnd + 1
                    if t == myslot:
                        order = S["rank_S1"] if st == "S1" else S["rank_S0"]
                        p = our_pick(st, order, taken, pos, cnt[t], rnd, left,
                                     S["Ev"], Rrep, rosters[t])
                    else:
                        p, j = opp_pick(boards[t], ptr[t], taken, pos, cnt[t], left)
                        ptr[t] = j
                    taken[p] = True
                    cnt[t][pos[p]] += 1
                    rosters[t].append(p)
                    if st == "S0" and sim < 20:
                        drafted_slot.setdefault(p, []).append(k + 1)
                sc = {}
                for t in range(NTEAM):
                    r14 = score_roster(S["wkm"], pos, rosters[t], 1, 14)
                    r17 = score_roster(S["wkm"], pos, rosters[t], 15, 17)
                    sc[t] = (r14, r17)
                mine = sc[myslot]
                ranks14 = 1 + sum(1 for t in range(NTEAM) if sc[t][0] > mine[0])
                cm = cnt[myslot]
                recs.append(dict(year=y, slot=myslot + 1, sim=sim, strat=st,
                                 pts14=mine[0], pts17=mine[1], pts_all=mine[0] + mine[1],
                                 pts_static=score_static(S["wkm"], pos, rosters[myslot]),
                                 nQB=cm[0], nRB=cm[1], nWR=cm[2], nTE=cm[3],
                                 rank14=ranks14, playoff=int(ranks14 <= (4 if NTEAM == 10 else 5)),
                                 champ=int(ranks14 == 1),
                                 opp_mean14=np.mean([sc[t][0] for t in range(NTEAM) if t != myslot])))
    for p, v in drafted_slot.items():
        calib.append(dict(year=y, pid=S["pid"][p], name=S["name"][p], pos=p,
                          adp=adp[p], ffc_stdev=sd[p], sim_mean=np.mean(v),
                          sim_sd=np.std(v, ddof=1) if len(v) > 1 else np.nan, n=len(v)))
    print(f"  {y} done  {time.time()-t0:.0f}s", flush=True)

R = pd.DataFrame(recs)
